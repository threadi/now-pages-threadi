declare(strict_types=1);

// prevent direct access.
defined( 'ABSPATH' ) || exit;

// do nothing if PHP-version is not 8.2 or newer.
if ( PHP_VERSION_ID < 80200 ) { // @phpstan-ignore if.alwaysFalse,smaller.alwaysFalse
	return;
}

use ThreadiNowPages\Plugin\Activation;
use ThreadiNowPages\Plugin\Deactivation;
use ThreadiNowPages\Plugin\Init;

// get plugin-path.
const NOWPAGES_PLUGIN = __FILE__;

// get plugin-version.
const NOWPAGES_PLUGIN_VERSION = '@@VersionNumber@@';

// get autoloader generated by composer.
require_once __DIR__ . '/vendor/autoload.php';

// register the few hooks which are needed while the plugins are loaded.
Init::get_instance()->early_init();

// add tasks for activation and deactivation.
register_activation_hook( __FILE__, array( Activation::get_instance(), 'run' ) );
register_deactivation_hook( __FILE__, array( Deactivation::get_instance(), 'run' ) );

// initialize plugin after all plugins have been loaded, so they could use our hooks.
if ( did_action( 'plugins_loaded' ) > 0 ) {
	// run it directly if this file is loaded later, e.g. during the activation of this plugin.
	Init::get_instance()->init();
} else {
	add_action( 'plugins_loaded', array( Init::get_instance(), 'init' ) );
}
